import { describe, expect, it } from "vitest";
import type { MarketplaceEntry } from "@/lib/api";
import {
    filterMarketplaceEntries,
    marketplaceAccessLabel,
    marketplaceChosen,
    marketplaceNeedsLabel,
    marketplaceTimeLabel,
    marketplaceToggleChoice,
    marketplaceTypedInputs,
    marketplaceVerifiedLabel,
    missingRequiredInputs,
} from "../marketplace-format";

const entry = (over: Partial<MarketplaceEntry> = {}): MarketplaceEntry => ({
    slug: "twenty", name: "Twenty", category: "CRM", label: "Open-source CRM", logo: null, needs: ["PostgreSQL", "Redis"],
    inputs: [], access: { kind: "app" },
    source: { kind: "Official image", image: "twentycrm/twenty:latest", repository: "https://github.com/twentyhq/twenty" },
    verified: null, ...over,
});

describe("Marketplace labels", () => {
    it("shows no time and Not tested yet until a deploy was measured", () => {
        expect(marketplaceTimeLabel(entry())).toBeNull();
        expect(marketplaceVerifiedLabel(entry())).toBe("Not tested yet");
    });

    it("rounds a measured deploy to whole minutes, never below one", () => {
        const verified = (seconds: number) => entry({ verified: { at: "2026-10-23T00:00:00Z", seconds, image: "x@sha256:a" } });
        expect(marketplaceTimeLabel(verified(300))).toBe("About 5 min");
        expect(marketplaceTimeLabel(verified(20))).toBe("About 1 min");
        expect(marketplaceVerifiedLabel(verified(300))).toBe("Verified");
    });

    it("says Nothing else when the app needs no database", () => {
        expect(marketplaceNeedsLabel(entry({ needs: [] }))).toBe("Nothing else");
        expect(marketplaceNeedsLabel(entry())).toBe("PostgreSQL, Redis");
    });
});

describe("filterMarketplaceEntries", () => {
    const list = [entry(), entry({ slug: "n8n", name: "n8n", category: "Automation", label: "Workflow automation" })];

    it("filters by category and by text, case-insensitively", () => {
        expect(filterMarketplaceEntries(list, "All", "")).toHaveLength(2);
        expect(filterMarketplaceEntries(list, "CRM", "").map((e) => e.slug)).toEqual(["twenty"]);
        expect(filterMarketplaceEntries(list, "All", "WORKFLOW").map((e) => e.slug)).toEqual(["n8n"]);
        expect(filterMarketplaceEntries(list, "CRM", "workflow")).toEqual([]);
    });
});

describe("Marketplace sign-in and typed settings", () => {
    const withInputs = entry({
        inputs: [
            { key: "EMAIL", label: "Your email", help: null, required: true, secret: false },
            { key: "API_KEY", label: "API key", help: "Optional.", required: false, secret: true },
        ],
    });

    it("describes who can open the app in one short state", () => {
        expect(marketplaceAccessLabel(entry({ access: { kind: "login", label: "Password", runsCode: false } }))).toBe("Password generated by Opslin");
        expect(marketplaceAccessLabel(entry({ access: { kind: "open", warning: "No sign-in." } }))).toBe("None");
        expect(marketplaceAccessLabel(entry())).toBe("Created when you first open it");
        expect(marketplaceAccessLabel(entry({ access: { kind: "app", label: "You create the admin", note: "Run the helper." } }))).toBe("You create the admin");
    });

    it("lists the required settings that are still empty, ignoring spaces and optional ones", () => {
        expect(missingRequiredInputs(withInputs, {})).toEqual(["Your email"]);
        expect(missingRequiredInputs(withInputs, { EMAIL: "   " })).toEqual(["Your email"]);
        expect(missingRequiredInputs(withInputs, { EMAIL: "me@example.org" })).toEqual([]);
        expect(missingRequiredInputs(entry(), {})).toEqual([]);
    });

    it("sends only the declared settings, trimmed, without the empty ones", () => {
        expect(marketplaceTypedInputs(withInputs, { EMAIL: " me@example.org ", API_KEY: "  ", OTHER: "x" })).toEqual({ EMAIL: "me@example.org" });
        expect(marketplaceTypedInputs(entry(), { EMAIL: "x" })).toEqual({});
    });
});

describe("Marketplace tool picker", () => {
    const picker = {
        key: "WORKBENCH_TOOLS", label: "Tools", help: null, required: true, secret: false, defaultValue: "jcode,claude",
        choices: [{ value: "jcode", label: "jcode" }, { value: "claude", label: "Claude Code" }, { value: "codex", label: "OpenAI Codex" }],
    };
    const withPicker = entry({ inputs: [picker] });

    it("starts with its default and counts it as filled", () => {
        expect(marketplaceChosen(picker, {})).toEqual(["jcode", "claude"]);
        expect(missingRequiredInputs(withPicker, {})).toEqual([]);
        expect(marketplaceTypedInputs(withPicker, {})).toEqual({ WORKBENCH_TOOLS: "jcode,claude" });
    });

    it("ticks and clears choices, keeping the listed order", () => {
        expect(marketplaceToggleChoice(picker, {}, "codex", true)).toBe("jcode,claude,codex");
        expect(marketplaceToggleChoice(picker, { WORKBENCH_TOOLS: "codex" }, "jcode", true)).toBe("jcode,codex");
        expect(marketplaceToggleChoice(picker, {}, "claude", false)).toBe("jcode");
        expect(marketplaceToggleChoice(picker, { WORKBENCH_TOOLS: "jcode" }, "jcode", false)).toBe("");
    });

    it("needs at least one tool once the person clears them all", () => {
        expect(missingRequiredInputs(withPicker, { WORKBENCH_TOOLS: "" })).toEqual(["Tools"]);
        expect(marketplaceTypedInputs(withPicker, { WORKBENCH_TOOLS: "" })).toEqual({});
    });
});
