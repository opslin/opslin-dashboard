import type { MarketplaceEntry } from "@/lib/api";

/** "About 5 min" only from a measured deploy; an entry nobody has deployed has no time to show. */
export function marketplaceTimeLabel(entry: MarketplaceEntry): string | null {
    if (!entry.verified) return null;
    const minutes = Math.max(1, Math.round(entry.verified.seconds / 60));
    return `About ${minutes} min`;
}

export function marketplaceVerifiedLabel(entry: MarketplaceEntry): string {
    return entry.verified ? "Verified" : "Not tested yet";
}

export function filterMarketplaceEntries(entries: MarketplaceEntry[], category: string, query: string): MarketplaceEntry[] {
    const needle = query.trim().toLowerCase();
    return entries.filter((entry) => {
        if (category !== "All" && entry.category !== category) return false;
        if (!needle) return true;
        return `${entry.name} ${entry.label} ${entry.category}`.toLowerCase().includes(needle);
    });
}

export function marketplaceNeedsLabel(entry: MarketplaceEntry): string {
    return entry.needs.length > 0 ? entry.needs.join(", ") : "Nothing else";
}

/** Who can open the app, as one short state. */
export function marketplaceAccessLabel(entry: MarketplaceEntry): string {
    if (entry.access.kind === "login") return `${entry.access.label} generated by Opslin`;
    if (entry.access.kind === "open") return "None";
    return entry.access.label ?? "Created when you first open it";
}

/** What an input holds right now: what was typed, else the picker's starting choice, else nothing. */
export function marketplaceInputValue(input: MarketplaceEntry["inputs"][number], values: Record<string, string>): string {
    return values[input.key] ?? input.defaultValue ?? "";
}

/** The ticked values of a picker as a list. */
export function marketplaceChosen(input: MarketplaceEntry["inputs"][number], values: Record<string, string>): string[] {
    return marketplaceInputValue(input, values).split(",").map((part) => part.trim()).filter(Boolean);
}

/** The picker's new value after one choice is ticked or cleared, kept in the order the choices are listed. */
export function marketplaceToggleChoice(input: MarketplaceEntry["inputs"][number], values: Record<string, string>, choice: string, on: boolean): string {
    const chosen = new Set(marketplaceChosen(input, values));
    if (on) chosen.add(choice); else chosen.delete(choice);
    return (input.choices ?? []).map((item) => item.value).filter((value) => chosen.has(value)).join(",");
}

/** The labels of required settings that are still empty. */
export function missingRequiredInputs(entry: MarketplaceEntry, values: Record<string, string>): string[] {
    return entry.inputs.filter((input) => input.required && !marketplaceInputValue(input, values).trim()).map((input) => input.label);
}

/** What is sent to the API: only the settings the entry declares, trimmed, empty ones left out. */
export function marketplaceTypedInputs(entry: MarketplaceEntry, values: Record<string, string>): Record<string, string> {
    const typed: Record<string, string> = {};
    for (const input of entry.inputs) {
        const value = marketplaceInputValue(input, values).trim();
        if (value) typed[input.key] = value;
    }
    return typed;
}
